// ==================== ЗАДАНИЕ 2 ====================
void task2() {
    int n;
    std::cout << "=== Задание 2 ===\n";
    std::cout << "Введите положительное целое число n: ";
    std::cin >> n;

    if (n <= 0) {
        std::cerr << "Ошибка: число должно быть положительным.\n";
        return;
    }

    int remainder = n % 2;
    int last_digit = n % 10;

    std::cout << "n % 2 = " << remainder << "\n";
    std::cout << "Число " << (remainder == 0 ? "чётное" : "нечётное") << "\n";
    std::cout << "Последняя цифра (n % 10) = " << last_digit << "\n";
}

// ==================== ЗАДАНИЕ 3 ====================
void task3() {
    double balance, amount;
    std::cout << "\n=== Задание 3 ===\n";
    std::cout << "Введите баланс на счёте: ";
    std::cin >> balance;
    std::cout << "Введите сумму для снятия: ";
    std::cin >> amount;

    if (amount <= 0) {
        std::cout << "Отказ: сумма должна быть положительной.\n";
        return;
    }
    if (amount > balance) {
        std::cout << "Отказ: недостаточно средств на счёте.\n";
        return;
    }
    // Проверка кратности 10 (работаем в копейках для точности)
    long long amount_cents = static_cast<long long>(amount * 100 + 0.5);
    if (amount_cents % 1000 != 0) { // 10.00 = 1000 копеек
        std::cout << "Отказ: сумма должна быть кратна 10.\n";
        return;
    }

    balance -= amount;
    std::cout << "Выдача одобрена. Остаток на счёте: " << balance << "\n";
}

